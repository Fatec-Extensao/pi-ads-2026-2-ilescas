-- Tabela GestorEducacional
CREATE TABLE GestorEducacional (
    idGestor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR2(255) NOT NULL,
    senhaHash VARCHAR2(255) NOT NULL
);

-- Tabela Pesquisa
CREATE TABLE Pesquisa (
    idPesquisa NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(255) NOT NULL,
    descricao VARCHAR2(4000),
    dataInicio DATE,
    dataFim DATE,
    status VARCHAR2(50),
    idGestor NUMBER NOT NULL,
    FOREIGN KEY (idGestor) REFERENCES GestorEducacional(idGestor)
);

-- Tabela CategoriaParticipante
CREATE TABLE CategoriaParticipante (
    idCategoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(255) NOT NULL,
    idPesquisa NUMBER NOT NULL,
    FOREIGN KEY (idPesquisa) REFERENCES Pesquisa(idPesquisa)
);

-- Tabela Questionario
CREATE TABLE Questionario (
    idQuestionario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idCategoria NUMBER NOT NULL UNIQUE,
    FOREIGN KEY (idCategoria) REFERENCES CategoriaParticipante(idCategoria)
);

-- Tabela Questao
CREATE TABLE Questao (
    idQuestao NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado VARCHAR2(4000) NOT NULL,
    tipoQuestao VARCHAR2(100),
    limiteRespostas NUMBER,
    validacaoFormato VARCHAR2(255),
    idQuestionario NUMBER NOT NULL,
    FOREIGN KEY (idQuestionario) REFERENCES Questionario(idQuestionario)
);

-- Tabela Alternativa
CREATE TABLE Alternativa (
    idAlternativa NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR2(255) NOT NULL,
    idQuestao NUMBER NOT NULL,
    FOREIGN KEY (idQuestao) REFERENCES Questao(idQuestao)
);

-- Tabela SenhaAcesso
CREATE TABLE SenhaAcesso (
    idSenha NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(100) NOT NULL UNIQUE,
    utilizada NUMBER(1) DEFAULT 0,
    idCategoria NUMBER NOT NULL,
    FOREIGN KEY (idCategoria) REFERENCES CategoriaParticipante(idCategoria)
);

-- Tabela Resposta
CREATE TABLE Resposta (
    idResposta NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    textoResposta VARCHAR2(4000),
    idQuestao NUMBER NOT NULL,
    idSenha NUMBER NOT NULL,
    FOREIGN KEY (idQuestao) REFERENCES Questao(idQuestao),
    FOREIGN KEY (idSenha) REFERENCES SenhaAcesso(idSenha)
);